/** rev.3's original three reference patterns, plus the two the Final Module 1 Audio Integration
 *  Pass added once the remaining 17 units' own finalized scripts existed: 'TRANSFER' (every Bank
 *  Dig's own post-practice narration) and 'independent practice' (Story 1-6/zurui's own — the
 *  Architect's own label, explicitly "not a checkpoint"). See `audioPlacement` below for what
 *  each one actually means for WHEN a mission's audio plays — the single source of truth
 *  src/shell/MissionShell.tsx's screen routing reads instead of comparing role strings itself. */
export type AudioRole = 'MODEL' | 'GUIDED' | 'CHECKPOINT' | 'TRANSFER' | 'independent practice';

/**
 * Where a mission's own registered audio plays, derived purely from its `role`:
 * - 'pre' (MODEL/GUIDED): before the child's own practice, reached from `chooseCoop` — for
 *   both solo and co-play.
 * - 'post-gated' (CHECKPOINT): strictly after the child's own work, teach-back AND the M2b
 *   parent confirmation — reached only from 'stage-teachback's own return-to-child action, so
 *   never in solo play (solo never reaches teach-back at all).
 * - 'post-ungated' (TRANSFER, 'independent practice'): immediately after the child's own dig
 *   work finishes (`MissionStage`'s onComplete), in BOTH solo and co-play — never gated behind
 *   the parent hand-off ritual the way CHECKPOINT is. This is the Architect's own "DO -> LISTEN
 *   (-> USE)" shape for every Bank Dig and for 1-6, which is explicitly "not a checkpoint" even
 *   though it also plays after the child's own work.
 */
export function audioPlacement(role: AudioRole): 'pre' | 'post-gated' | 'post-ungated' {
  if (role === 'MODEL' || role === 'GUIDED') return 'pre';
  if (role === 'CHECKPOINT') return 'post-gated';
  return 'post-ungated';
}

export interface AudioScript {
  /** The Mission this script belongs to — src/audio/registry.ts's own lookup key. */
  missionId: string;
  role: AudioRole;
  /**
   * Whether this script's real, per-line TTS audio assets have actually been generated yet.
   * `'pending-production'` — the common case today for all three Audio Reference Slice scripts:
   * no MP3s exist anywhere in the repo, `scripts/audio/generate-*.ts` hasn't been run (blocked on
   * a one-time Google Cloud Text-to-Speech credential — see that script's own header), and
   * src/stage/AudioScene.tsx correctly has nothing to play — it falls back to its existing
   * text-anchor screen (the mission's own `robotLine`, tap-to-advance), never fabricated or
   * placeholder audio. `'ready'` is reserved for once real assets under public/audio/... exist
   * and this script has been extended with the line-by-line manifest that plays them — do not
   * set it before that's true.
   */
  audioStatus: 'pending-production' | 'ready';
  /**
   * rev.3's own anchor requirement: "every ROBOT line must be the authored robotSays text, word
   * for word... If the audio and the stage differ by even one word, that anchor breaks." This is
   * that mission's dig phase's own layer-0 `robotSays`, copied verbatim from its s2.json — never
   * new copy authored here. tests/Audio.test.tsx asserts this field still matches each mission's
   * real content, so drift is caught before it ever reaches a recording session.
   */
  robotLine: string;
  /**
   * MODEL only (rev.3 §E, "One engine dependency to flag"): the dig layer indices (0-based) this
   * script demonstrates in full before the child ever plays them. A play at one of these layers
   * is primed — the child has just heard the answer — so src/stage/MissionStage.tsx suppresses
   * its `onUse` evidence entirely (no `use`, no `apt_use`, no rung advancement, no milestone
   * credit) for exactly these layers; every other layer records exactly as it always has.
   * Deliberately carried on the script itself, never as a standalone field anywhere else, so the
   * guard can never be enabled independently of the audio that justifies it — src/shell/
   * MissionShell.tsx only ever reads it off the mission's own registered AudioScript.
   */
  demonstratedLayers?: number[];
  /**
   * The real, per-line playback manifest once `audioStatus` is `'ready'` — GUIDE/PONTA/ROBOT
   * dialogue in order, each pointing at its own committed MP3 (public/audio/...) and the gap to
   * hold before the next line starts. Absent whenever `audioStatus` is `'pending-production'`;
   * src/stage/AudioScene.tsx branches on this field's presence — with it, a real sequential
   * playback screen; without it, the existing text-anchor fallback (the mission's own
   * `robotLine`, tap-to-advance). Generated by scripts/audio/generate-1-1-model.ts /
   * generate_1_1_model.py, never hand-authored.
   */
  lines?: AudioLine[];
}

export interface AudioLine {
  speaker: 'GUIDE' | 'PONTA' | 'ROBOT';
  text: string;
  audioUrl: string;
  pauseAfterMs: number;
}
